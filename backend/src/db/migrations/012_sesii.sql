-- ============================================================================
-- 012 — Сесии и устройства
--
-- Дотук един акаунт можеше да се ползва едновременно от неограничен брой
-- устройства: токенът е самодостатъчен лист хартия, сървърът не помнеше на
-- кого го е дал. Един платен акаунт стигаше за цял курс.
--
-- Тази таблица дава на сървъра памет: всяко влизане е ред тук, всеки токен
-- носи номера на своя ред, а щом редът бъде прекратен — токенът спира да
-- важи, независимо че още не е изтекъл.
--
-- Редовете НЕ се трият при излизане, а се отбелязват като прекратени. Така
-- остава история: от колко различни устройства се влиза в този акаунт, от
-- колко различни мрежи и колко често се редуват. Точно това отличава
-- „човек с телефон и лаптоп“ от „акаунт, който обикаля курса“.
--
-- Всичко е с IF NOT EXISTS — миграцията може да се пусне повторно безопасно.
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

CREATE TABLE IF NOT EXISTS user_sessions (
  id             UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id        UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  -- Идентификатор на устройството: случайно число, което браузърът си пази
  -- и връща при всяко влизане. Служи за едно нещо — повторният вход от
  -- СЪЩОТО устройство да не се брои за ново устройство и да не изхвърля
  -- собственика му. Стойността идва от клиента, тоест може да се подправи;
  -- затова на нея не виси нито едно разрешение. Ограничението за брой
  -- сесии се смята по редовете тук, не по това поле.
  device_id      VARCHAR(64),
  device_label   VARCHAR(120),          -- „Chrome на Windows“ — за човешки очи
  user_agent     TEXT,
  ip_address     VARCHAR(64),

  created_at     TIMESTAMP NOT NULL DEFAULT NOW(),
  last_seen_at   TIMESTAMP NOT NULL DEFAULT NOW(),
  expires_at     TIMESTAMP NOT NULL,

  revoked_at     TIMESTAMP,
  -- Защо е прекратена. Стига до потребителя като изречение, а не като код:
  --   drugo-ustrojstvo — влезли са от друго устройство
  --   izhod            — сам е натиснал „Изход“
  --   izhod-vsichki    — „Изход от всички устройства“
  --   nova-parola      — смяна или възстановяване на парола
  --   administrator    — прекратена от админ
  --   izteklo          — изтекъл срок
  revoked_reason VARCHAR(40)
);

-- Горещата заявка: „активните сесии на този потребител“. Частичният индекс
-- покрива само тях — прекратените редове растат безкрайно, но не тежат.
CREATE INDEX IF NOT EXISTS idx_sessions_active
  ON user_sessions (user_id, last_seen_at DESC)
  WHERE revoked_at IS NULL;

-- За историята: колко различни устройства е видял този акаунт напоследък.
CREATE INDEX IF NOT EXISTS idx_sessions_user_created
  ON user_sessions (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_sessions_device
  ON user_sessions (user_id, device_id);

-- ------------------------------------------------------------- лимит на акаунт
-- По подразбиране 1: един акаунт = едно устройство в даден момент. Колоната е
-- на потребителя, а не константа в кода, защото ще има изключения — учител с
-- лаптоп и таблет, служебен акаунт, човек, който е купил семеен достъп. Тогава
-- се вдига на този акаунт, без да се пипа кодът и без да се отпуска за всички.
ALTER TABLE users ADD COLUMN IF NOT EXISTS max_sessions INTEGER NOT NULL DEFAULT 1;

-- Предпазител срещу глупава грешка в админския панел (0 или отрицателно
-- число би заключило акаунта завинаги; 10 вече не е „моите устройства“).
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'users_max_sessions_razumno'
  ) THEN
    ALTER TABLE users
      ADD CONSTRAINT users_max_sessions_razumno
      CHECK (max_sessions BETWEEN 1 AND 10);
  END IF;
END $$;
